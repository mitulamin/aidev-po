#!/usr/bin/env python3
"""Generate .cursor/ from the sources in agents/, skills/ and commands/.

Usage:
  scripts/build-agents.py          write the files
  scripts/build-agents.py --check  exit 1 if any generated file is stale (for CI)

Standard library only. The same approach as ai-sdlc-loop's scripts/build-agents.py and
scripts/install-harness.py: the sources stay the source of truth, and the harness layout is
generated from them. Cursor is the first harness; AGENTS.md covers the rest.

Sources (each needs `name` and `description` in its front matter; `name` matches the file or
folder name; README.md is not a source):

  agents/<name>.md          -> .cursor/agents/<name>.md
  skills/<name>/SKILL.md    -> .cursor/skills/<name>/SKILL.md (other files in the folder are copied as they are)
  commands/<name>.md        -> .cursor/skills/po-<name>/SKILL.md, a slash command /po-<name> that
                               runs only when the user types it (Cursor treats commands as skills)

Every generated markdown file carries a GENERATED marker after its front matter. Only files this
script manages are touched: a folder under .cursor/agents or .cursor/skills is managed if its
SKILL.md or agent file carries the marker. Anything else in .cursor/ is left alone.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / ".cursor"
COMMAND_PREFIX = "po-"
MARKER = "<!-- GENERATED by scripts/build-agents.py from agents/, skills/ and commands/. Do not edit; edits are overwritten. -->"
SLUG = re.compile(r"[a-z0-9]+(-[a-z0-9]+)*")
YAML_PLAIN = re.compile(r"[A-Za-z][A-Za-z0-9_.-]*")
YAML_RESERVED = {"true", "false", "yes", "no", "on", "off", "null", "~"}
COMMAND_PREAMBLE = ("Act as the coordinator `po` for this command: read `.cursor/agents/po.md` and follow it. "
                    "Start each producer and reviewer it names as a subagent from the same folder.\n\n"
                    "Any text the user typed after the command is the argument.\n")


def parse_front(text):
    """Split '---' front matter from the body. Values are JSON where they parse, else plain strings."""
    if not text.startswith("---\n") or "\n---\n" not in text[4:]:
        return None, text
    end = text.index("\n---\n", 4)
    front = {}
    for line in text[4:end].splitlines():
        key, sep, value = line.partition(":")
        if not sep:
            continue
        value = value.strip()
        try:
            front[key.strip()] = json.loads(value)
        except json.JSONDecodeError:
            front[key.strip()] = value
    return front, text[end + 5:]


def yaml_scalar(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    v = str(v)
    if YAML_PLAIN.fullmatch(v) and v.lower() not in YAML_RESERVED:
        return v
    return json.dumps(v, ensure_ascii=False)


def render(front, body):
    head = "\n".join(f"{k}: {yaml_scalar(v)}" for k, v in front.items())
    return f"---\n{head}\n---\n{MARKER}\n\n{body.lstrip(chr(10))}".rstrip("\n") + "\n"


def read_source(path, expected_name, errors):
    rel = path.relative_to(ROOT)
    front, body = parse_front(path.read_text(encoding="utf-8"))
    if front is None:
        errors.append(f"{rel}: needs front matter between --- lines")
        return None, None
    name, desc = front.get("name"), front.get("description")
    if not isinstance(name, str) or not SLUG.fullmatch(name):
        errors.append(f"{rel}: name must be a lowercase slug, got {name!r}")
    elif name != expected_name:
        errors.append(f"{rel}: name {name!r} must match {expected_name!r}")
    if not isinstance(desc, str) or not desc.strip():
        errors.append(f"{rel}: description is required")
    return front, body


def build():
    """Return ({relative output path: text or bytes}, errors)."""
    files, errors, seen = {}, [], {}

    def claim(kind, name):
        if name in seen:
            errors.append(f"{kind} {name!r} clashes with {seen[name]} {name!r}")
        seen[name] = kind

    for path in sorted((ROOT / "agents").glob("*.md")):
        if path.name == "README.md":
            continue
        front, body = read_source(path, path.stem, errors)
        if front is None:
            continue
        out = {"name": front.get("name"), "description": front.get("description"), "model": "inherit"}
        files[f"agents/{path.name}"] = render(out, body)

    for folder in sorted(p for p in (ROOT / "skills").iterdir() if p.is_dir()):
        skill = folder / "SKILL.md"
        if not skill.exists():
            errors.append(f"{folder.relative_to(ROOT)}: SKILL.md is missing")
            continue
        front, body = read_source(skill, folder.name, errors)
        if front is None:
            continue
        claim("skill", folder.name)
        out = {"name": front.get("name"), "description": front.get("description")}
        for key, dest in (("licence", "license"), ("license", "license"), ("metadata", "metadata")):
            if key in front:
                out[dest] = front[key]
        files[f"skills/{folder.name}/SKILL.md"] = render(out, body)
        for extra in sorted(p for p in folder.rglob("*") if p.is_file() and p != skill):
            files[f"skills/{folder.name}/{extra.relative_to(folder).as_posix()}"] = extra.read_bytes()

    for path in sorted((ROOT / "commands").glob("*.md")):
        if path.name == "README.md":
            continue
        front, body = read_source(path, path.stem, errors)
        if front is None:
            continue
        name = COMMAND_PREFIX + front["name"]
        claim("skill", name)
        out = {"name": name, "description": front.get("description"), "disable-model-invocation": True}
        files[f"skills/{name}/SKILL.md"] = render(out, COMMAND_PREAMBLE + "\n" + body.lstrip("\n"))
    return files, errors


def managed_files():
    """Files under .cursor/ that this script owns: carry the marker, or sit in a folder whose SKILL.md does."""
    found = set()
    agents = OUT / "agents"
    if agents.is_dir():
        found |= {f"agents/{p.name}" for p in agents.glob("*.md") if MARKER in p.read_text(encoding="utf-8")}
    skills = OUT / "skills"
    if skills.is_dir():
        for folder in (p for p in skills.iterdir() if p.is_dir()):
            skill = folder / "SKILL.md"
            if skill.exists() and MARKER in skill.read_text(encoding="utf-8"):
                found |= {f"skills/{folder.name}/{p.relative_to(folder).as_posix()}" for p in folder.rglob("*") if p.is_file()}
    return found


def as_bytes(content):
    return content.encode("utf-8") if isinstance(content, str) else content


def main(argv):
    files, errors = build()
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    stale = sorted(rel for rel, content in files.items()
                   if not (OUT / rel).exists() or (OUT / rel).read_bytes() != as_bytes(content))
    orphans = sorted(managed_files() - set(files))
    if "--check" in argv:
        for rel in stale:
            print(f".cursor/{rel}: out of date; run scripts/build-agents.py", file=sys.stderr)
        for rel in orphans:
            print(f".cursor/{rel}: generated file with no source; run scripts/build-agents.py", file=sys.stderr)
        return 1 if stale or orphans else 0
    for rel in stale:
        target = OUT / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(as_bytes(files[rel]))
    for rel in orphans:
        (OUT / rel).unlink()
        parent = (OUT / rel).parent
        if parent != OUT / "agents" and not any(parent.iterdir()):
            parent.rmdir()
    print(f"wrote {len(stale)} file(s), removed {len(orphans)}; {len(files)} generated in .cursor/")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
