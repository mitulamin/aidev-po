def load_harnesses():
    doc = json.loads((DATA / "harnesses.json").read_text(encoding="utf-8"))
    if doc.get("schema_version") != SCHEMA_VERSION:
        raise SystemExit(f"data/harnesses.json: schema_version is {doc.get('schema_version')!r}, this script expects {SCHEMA_VERSION}")
    return doc


def git_ref():
    try:
        out = subprocess.run(["git", "-C", str(ROOT), "rev-parse", "HEAD"], capture_output=True, text=True, check=True)
        return out.stdout.strip() or "unknown"
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def detect_tools(project):
    """Other tools already registered in the project: a list of {tool, format, evidence}.

    Two formats are recognised. "legacy" is how ai-sdlc-loop registered before a shared convention existed:
    its always-on rule, its .ai-sdlc/ folder, or agents that carry its provenance comment. "manifest" is the
    drop-in convention aidev-po uses itself: a top-level .<tool>/install.json that names its tool.
    """
    project = Path(project)
    found = []
    evidence = []
    if (project / SDLC_LEGACY_RULE).is_file():
        evidence.append(SDLC_LEGACY_RULE)
    if (project / ".ai-sdlc").is_dir():
        evidence.append(".ai-sdlc/")
    coordinator = project / ".cursor/agents/coordinator.md"
    if coordinator.is_file() and SDLC_PROVENANCE in coordinator.read_text(encoding="utf-8", errors="replace"):
        evidence.append(".cursor/agents/coordinator.md")
    if evidence:
        found.append({"tool": "ai-sdlc-loop", "format": "legacy", "evidence": evidence})
    for manifest in sorted(project.glob(f".*/{MANIFEST}")):
        try:
            tool = json.loads(manifest.read_text(encoding="utf-8")).get("tool")
        except (OSError, ValueError, AttributeError):
            continue
        if isinstance(tool, str) and tool and tool != TOOL:
            rel = manifest.relative_to(project).as_posix()
            found.append({"tool": tool, "format": "manifest", "evidence": [rel]})
    return found


class Installer:
    def __init__(self, harness_id, overlay=None):
        self.doc = load_harnesses()
        by_id = {h["id"]: h for h in self.doc["harnesses"]}
        if harness_id not in by_id:
            raise SystemExit(f"Unknown harness: {harness_id}. Known: {', '.join(by_id)}")
        self.h = by_id[harness_id]
        self.shared = self.doc["shared_dir"]
        self.ref = git_ref()
        self.overlay = Path(overlay) if overlay else None

    def rename(self, text):
        """Prefix the agents ai-sdlc-loop also has. Mentions of ai-sdlc-loop's own agents are left as they are."""
        names = self.h["agents"].get("rename", {})
        if not names:
            return text
        pattern = re.compile(r"(?<![\w.-])(" + "|".join(map(re.escape, names)) + r")(?![\w-])")
        agents_dir = self.h["agents"]["dir"] + "/"

        def sub(m):
            before = text[:m.start()]
            if before.endswith(RENAME_SKIP_AFTER) or (before.endswith("/") and not before.endswith(agents_dir)):
                return m.group(0)
            return names[m.group(1)]
        return pattern.sub(sub, text)

    def localise(self, text):
        """Point the installed copy at the texts in this project, not at an aidev-po checkout."""
        for old, new in LOCALISE:
            text = text.replace(old, new)
        return text

    def rewrite_paths(self, text):
        """Point scripts/, schemas/, templates/, docs, examples and skills at the installed copies."""
        rw = self.h["rewrite"]
        text = re.sub(r"(?<![\w/.-])(" + "|".join(map(re.escape, rw["dirs"])) + r")/", rf"{self.shared}/\1/", text)
        docs = "|".join(map(re.escape, rw["docs"]))
        text = re.sub(rf"(?<![\w/.-])docs/({docs})", rf"{self.shared}/docs/\1", text)
        text = re.sub(r"(?<![\w/.-])examples/", f"{self.shared}/examples/", text)
        text = re.sub(r"(?<![\w/.-])skills/", ".cursor/skills/", text)
        commands = ROOT / "commands"
        if commands.is_dir():
            for path in sorted(commands.glob("*.md")):
                if path.name == "README.md":
                    continue
                text = text.replace(f"commands/{path.name}", f".cursor/skills/po-{path.stem}/SKILL.md")
        return text

    def harness_copy(self, text):
        """Rename and rewrite paths, except on the GENERATED marker line, which stays as it is."""
        lines = text.split("\n")
        return "\n".join(
            line if line.startswith(MARKER_PREFIX) else self.rewrite_paths(self.rename(self.localise(line)))
            for line in lines
        )

    def plan(self):
        """{project-relative path: bytes} for everything this harness installs."""
        files = {}
        src = ROOT / self.h["source"]
        renames = self.h["agents"].get("rename", {})
        for kind in ("agents", "skills"):
            base = src / kind
            if not base.is_dir():
                raise SystemExit(f"{base} is missing; run scripts/build-agents.py first")
            for path in sorted(p for p in base.rglob("*") if p.is_file()):
                rel = path.relative_to(base).as_posix()
                if kind == "agents":
                    stem = rel[:-3] if rel.endswith(".md") else rel
                    rel = renames.get(stem, stem) + rel[len(stem):]
                data = path.read_bytes()
                if path.suffix in TEXT_SUFFIXES:
                    data = self.harness_copy(data.decode("utf-8")).encode("utf-8")
                files[f"{self.h[kind]['dir']}/{rel}"] = data
        rules = self.h["rules"]
        rule = (ROOT / rules["template"]).read_text(encoding="utf-8")
        files[f"{rules['dir']}/{rules['file']}"] = rule.encode("utf-8")

        rt = self.h["runtime"]
        for name in rt["scripts"]:
            files[f"{self.shared}/scripts/{name}"] = (ROOT / "scripts" / name).read_bytes()
        for sub in ("schemas", "templates"):
            for path in sorted(p for p in (ROOT / sub).rglob("*") if p.is_file()):
                rel = path.relative_to(ROOT / sub).as_posix()
                if sub == "templates" and rel.startswith("bootstrap/"):
                    continue
                # Copy bytes, including through a source symlink, and never store a link.
                files[f"{self.shared}/{sub}/{rel}"] = path.read_bytes()
        for name in rt["docs"]:
            text = (ROOT / "docs" / name).read_text(encoding="utf-8")
            text = text.replace(SOURCE_NOTICE_URL, "../NOTICE.md")
            files[f"{self.shared}/docs/{name}"] = text.encode("utf-8")
        examples = ROOT / "examples"
        if examples.is_dir():
            for path in sorted(p for p in examples.rglob("*") if p.is_file()):
                rel = path.relative_to(examples).as_posix()
                if ".git" in Path(rel).parts:
                    continue
                files[f"{self.shared}/examples/{rel}"] = path.read_bytes()
        files[f"{self.shared}/LICENSE"] = (ROOT / "LICENSE").read_bytes()
        files[f"{self.shared}/LICENSE-CONTENT"] = (ROOT / "LICENSE-CONTENT").read_bytes()
        files[f"{self.shared}/NOTICE.md"] = INSTALLED_NOTICE.encode("utf-8")
        files[f"{self.shared}/.gitignore"] = b"# Where the products repo is, on this machine only.\naidev-po.local.json\n"

        if self.overlay:
            if not self.overlay.is_dir():
                raise SystemExit(f"--overlay {self.overlay} is not a folder")
            for path in sorted(p for p in self.overlay.rglob("*") if p.is_file()):
                rel = path.relative_to(self.overlay).as_posix()
                if rel in files or rel.startswith(f"{self.shared}/{MANIFEST}"):
                    raise SystemExit(f"--overlay would replace {rel}, which aidev-po installs itself")
                files[rel] = path.read_bytes()
        return files

    def manifest(self, files):
        doc = {
            "tool": TOOL,
            "convention": CONVENTION,
            "harness": self.h["id"],
            "source": {"repo": self.doc["repo_url"], "sha": self.ref},
            "files": {rel: sha256(data) for rel, data in sorted(files.items())},
        }
        return (json.dumps(doc, indent=2) + "\n").encode("utf-8")


def read_manifest(project, shared):
    path = project / shared / MANIFEST
    if not path.is_file():
        return {}
    try:
        return json.loads(path.read_text(encoding="utf-8")).get("files", {})
    except (ValueError, AttributeError):
        raise SystemExit(f"{path} is not valid JSON, so I cannot tell which files are aidev-po's; I have changed nothing.")


def install(project, harness_id, overlay=None):
    """Return (installer, report) where report has written, unchanged, removed and others (detected tools)."""
    inst = Installer(harness_id, overlay)
    project = Path(project)
    if not project.is_dir():
        raise SystemExit(f"{project} is not a folder")
    root = project.resolve()
    if root == ROOT or ROOT in root.parents:
        raise SystemExit(f"{project} is inside the aidev-po checkout itself, so I have changed nothing. Choose a place outside it.")
    files = inst.plan()
    manifest_rel = f"{inst.shared}/{MANIFEST}"
    files_with_manifest = dict(files)
    files_with_manifest[manifest_rel] = inst.manifest(files)

    previous = read_manifest(root, inst.shared)
    others = detect_tools(root)
    edited, clashes, writes, unchanged = [], [], {}, []
    for rel, data in sorted(files_with_manifest.items()):
        dest = root / rel
        owned = rel in previous and rel != manifest_rel
        if dest.is_symlink():
            (edited if owned else clashes).append(rel)
            continue
        if not dest.resolve().is_relative_to(root):
            raise SystemExit(f"{rel} is outside {project}")
        if dest.exists() and not dest.is_file():
            (edited if owned else clashes).append(rel)
        elif not dest.exists():
            writes[rel] = data
        elif dest.read_bytes() == data:
            unchanged.append(rel)
        elif rel in previous and sha256(dest.read_bytes()) == previous[rel]:
            writes[rel] = data
        elif rel == manifest_rel and previous:
            writes[rel] = data
        elif owned:
            edited.append(rel)
        else:
            clashes.append(rel)
    if edited or clashes:
        parts = []
        if edited:
            parts.append(
                "I detected local edits to aidev-po's own files. "
                "I halted rather than overwrite them, and nothing was written:\n" + "\n".join(edited)
            )
        if clashes:
            parts.append(
                "Refusing to overwrite files that are not aidev-po's, so I have changed nothing: " + ", ".join(clashes)
            )
        raise SystemExit("\n".join(parts))

    stale = [rel for rel, digest in previous.items() if rel not in files_with_manifest
             and (root / rel).is_file() and sha256((root / rel).read_bytes()) == digest]
    for rel, data in writes.items():
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    for rel in stale:
        (root / rel).unlink()
    return inst, {"written": sorted(writes), "unchanged": unchanged, "removed": stale, "others": others}


def main():
    args = sys.argv[1:]
    usage = "\n".join(__doc__.strip().split("\n\n")[0:2])
    if args in (["-h"], ["--help"]):
        print(usage)
        return 0
    if args == ["--list"]:
        for h in load_harnesses()["harnesses"]:
            print(f"{h['id']}\t{h['name']}")
        return 0
    if len(args) == 2 and args[0] == "--validate":
        return 0 if args[1] in [h["id"] for h in load_harnesses()["harnesses"]] else 1
    if len(args) == 2 and args[0] == "--detect":
        print(json.dumps(detect_tools(args[1]), indent=2))
        return 0
    overlay = os.environ.get(OVERLAY_ENV) or None
    if "--overlay" in args:
        i = args.index("--overlay")
        if i + 1 >= len(args):
            print("--overlay needs a folder", file=sys.stderr)
            return 2
        overlay = args[i + 1]
        del args[i:i + 2]
    if len(args) != 2 or args[0].startswith("-"):
        print(usage, file=sys.stderr)
        return 2
    inst, rep = install(args[0], args[1], overlay)
    for other in rep["others"]:
        print(f"Found {other['tool']} already registered here ({other['format']} format: {', '.join(other['evidence'])}). Left untouched.")
    if rep["written"]:
        print(f"Installed the {inst.h['name']} layout: wrote {len(rep['written'])} files, {len(rep['unchanged'])} already up to date, under {args[0]}")
    else:
        print(f"Already installed: all {len(rep['unchanged'])} files are up to date under {args[0]}. Nothing changed.")
    if rep["removed"]:
        print(f"Removed {len(rep['removed'])} files from an earlier aidev-po that it no longer installs.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
