#!/usr/bin/env python3
"""Install aidev-po into a project, in the layout a coding harness reads. Additive and idempotent.

Usage:
  scripts/install-harness.py <project-dir> <harness>   install into an existing project folder
  scripts/install-harness.py --list                     print each harness id and name
  scripts/install-harness.py --validate <harness>       exit 1 unless <harness> is known
  scripts/install-harness.py --detect <project-dir>     print the other tools already registered there

Options for the install form:
  --overlay DIR   also copy the files under DIR into the project (never over an existing file).
                  The generic extension point: nothing is overlaid unless this is given, or
                  AIDEV_PO_BOOTSTRAP_OVERLAY is set.

Standard library only. scripts/new-project.sh calls it. The layout per harness is data/harnesses.json
(the same shape as ai-sdlc-loop's); the sources are the generated .cursor/ folder, scripts/, schemas/
and templates/ as they are on disk, so run scripts/build-agents.py first if you changed agents/,
skills/ or commands/.

What it writes, all inside <project-dir>:
  .cursor/agents/, .cursor/skills/   the agents, skills and /po-* commands (two agent names are prefixed
                                     with po- so they cannot clash with ai-sdlc-loop's)
  .cursor/rules/aidev-po-bootstrap.mdc   the always-on pointer, aidev-po's registration in Cursor's rules layer
  .aidev-po/                         the scripts, schemas and templates the agents run, install.json (the
                                     registration manifest: every file written, with its hash), .gitignore

How it registers. Registration is a drop-in: aidev-po owns the files above and edits no file it did not
create. There is no shared registry file to merge into, so it does not matter which tool is installed
first. It never touches AGENTS.md, .ai-sdlc/ (the register included), another tool's rule, agent or skill,
MCP configuration, hooks, or editor settings.

Idempotent. A file that is already there with the same bytes is skipped. A file aidev-po wrote earlier
and has not been edited since is updated. A file aidev-po wrote that has since been edited is a local
edit: the installer stops, names each edited path, and writes nothing. Any other existing file is a
clash: the installer refuses and writes nothing at all. Files aidev-po wrote before, that are no longer
part of it and are unedited, are removed.

The copy is self-contained. Agents, skills, the rule, templates, scripts, schemas, the two docs and the
worked example are written into the project as ordinary files. Nothing is a symlink, and the installed
text does not point at the aidev-po checkout to read those texts. Licence texts are copied with them:
GPL-3.0 for scripts and schemas, CC BY-SA 4.0 for the writing, MIT for templates and the rule.
"""
